'''
Сортировка
массива из 0 и 1
➔ Дан массив, содержащий только
0 и 1.
➔ Напишите функцию, которая
сортирует его так, чтобы все нули
оказались в начале, а все единички —
в конце.
Решение должно быть in-place.
'''
def sb(arr):
  i = 0
  j = len(arr) - 1
  while i<j:
    if arr[i] == 1:
      arr[i], arr[j] = arr[j], arr[i]
      j-=1
    else:
      i+=1
  return arr
